"""Trips and their preferences, written by MOD-B03 (migration 0003, Appendix A.4).

``trips.plan_revision`` is the one column MOD-B08 writes, inside its edit and save transactions.
``trips.num_days`` is generated by the database and read-only here.
"""

import uuid
from datetime import date, datetime
from decimal import Decimal

from sqlalchemy import (
    ARRAY,
    CHAR,
    Boolean,
    Computed,
    Date,
    DateTime,
    ForeignKey,
    Integer,
    Numeric,
    SmallInteger,
    Text,
    text,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.db.models.base import Base


class Trip(Base):
    __tablename__ = "trips"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("profiles.id", ondelete="CASCADE")
    )
    destination_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("destinations.id", ondelete="RESTRICT")
    )
    title: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(Text, server_default=text("'draft'"))
    start_date: Mapped[date] = mapped_column(Date)
    end_date: Mapped[date] = mapped_column(Date)
    # Generated column: the database computes it, and the ORM never writes it.
    num_days: Mapped[int | None] = mapped_column(
        Integer, Computed("end_date - start_date + 1", persisted=True)
    )
    adults: Mapped[int] = mapped_column(SmallInteger, server_default=text("1"))
    children: Mapped[int] = mapped_column(SmallInteger, server_default=text("0"))
    group_needs: Mapped[list[str]] = mapped_column(ARRAY(Text), server_default=text("'{}'::text[]"))
    budget_amount: Mapped[Decimal | None] = mapped_column(Numeric(12, 2))
    budget_currency: Mapped[str | None] = mapped_column(CHAR(3))
    plan_revision: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    plan_stale: Mapped[bool] = mapped_column(Boolean, server_default=text("false"))
    deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("now()")
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("now()")
    )


class TripPreferences(Base):
    __tablename__ = "trip_preferences"

    trip_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("trips.id", ondelete="CASCADE"), primary_key=True
    )
    interests: Mapped[list[str]] = mapped_column(ARRAY(Text), server_default=text("'{}'::text[]"))
    pace: Mapped[str] = mapped_column(Text, server_default=text("'balanced'"))
    budget_priority: Mapped[str] = mapped_column(Text, server_default=text("'balanced'"))
    transport_pref: Mapped[str] = mapped_column(Text, server_default=text("'walking'"))
    accommodation_type: Mapped[str] = mapped_column(Text, server_default=text("'any'"))
    step_free_required: Mapped[bool] = mapped_column(Boolean, server_default=text("false"))
    notes: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("now()")
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("now()")
    )
